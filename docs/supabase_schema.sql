-- Web database for Expense Tracker.
--
-- The Android app keeps its own SQLite file and never reads these tables. This
-- schema is for the web build only: same shape as Drift schema v9, plus user_id
-- and RLS. Ids stay `bigint identity` so `TransactionEntity.id` remains an int:
-- casting a uuid through hashCode would make update and delete depend on a
-- collision instead of on the row's real id.
--
-- Run this whole file once in the Supabase SQL Editor.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- categories

create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  name        text not null check (char_length(name) between 1 and 50),
  type        text not null check (type in ('income', 'expense')),
  created_at  timestamptz not null default now(),
  unique (user_id, name, type)
);

create index if not exists categories_user_id_idx on public.categories (user_id);

alter table public.categories enable row level security;

drop policy if exists categories_owner on public.categories;
create policy categories_owner on public.categories
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ------------------------------------------------------------- subcategories

create table if not exists public.subcategories (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete cascade,
  name        text not null check (char_length(name) between 1 and 50),
  created_at  timestamptz not null default now(),
  unique (user_id, category_id, name)
);

create index if not exists subcategories_user_id_idx
  on public.subcategories (user_id);

alter table public.subcategories enable row level security;

drop policy if exists subcategories_owner on public.subcategories;
create policy subcategories_owner on public.subcategories
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- -------------------------------------------------------------- transactions

create table if not exists public.transactions (
  id             bigint generated by default as identity primary key,
  user_id        uuid not null references auth.users(id) on delete cascade,
  type           text not null check (type in ('income', 'expense')),
  amount         double precision not null check (amount > 0),
  category_id    bigint not null references public.categories(id),
  subcategory_id bigint references public.subcategories(id),
  note           text check (note is null or char_length(note) <= 500),
  date           timestamptz not null,
  created_at     timestamptz not null default now()
);

-- The date index is what makes the month, week and export reads stay fast as
-- the history grows. Every read is already scoped to one user by RLS, so
-- user_id leads the index.
create index if not exists transactions_user_date_idx
  on public.transactions (user_id, date desc);

alter table public.transactions enable row level security;

drop policy if exists transactions_owner on public.transactions;
create policy transactions_owner on public.transactions
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- ---------------------------------------------------------------- seed notes
--
-- Categories are seeded by the Flutter client after the first login, from the
-- same list the Android app ships. That keeps one source of truth for the names
-- (Salary, Freelance, Bonus, Gift, Allowance, Food, Other Needs,
-- Data/Internet Package, Coffee Shop, Fuel) and avoids a second seed list in SQL.
-- The unique constraints above make a repeated seed harmless if two tabs race.

-- --------------------------------------------------------------- grants
--
-- RLS decides *which* rows a user may see, but PostgreSQL still needs the
-- basic table privilege first. Without these GRANTs every request with the
-- anon key fails with 42501 before the policy is ever consulted.
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.categories,
  public.subcategories, public.transactions to authenticated;
grant usage, select on sequence public.categories_id_seq to authenticated;
grant usage, select on sequence public.subcategories_id_seq to authenticated;
grant usage, select on sequence public.transactions_id_seq to authenticated;
